def _db(tmp_path, pairs):
    db = tmp_path / "j.db"
    c = sqlite3.connect(db)
    c.execute("CREATE TABLE known_issue_models (issue_id INTEGER, make TEXT, model TEXT)")
    c.executemany("INSERT INTO known_issue_models VALUES (?,?,?)", pairs)
    c.commit(); c.close()
    return db


class TestCensus:
    def test_only_unknown_pairs_are_counted_with_their_rows(self, tmp_path):
        db = _db(tmp_path, [
            (1, "Honda", "PCX 150"), (2, "Honda", "PCX 150"),      # model-sourced: out
            (3, "Honda", "Africa Twin"),                           # ambiguous: out
            (4, "Honda", "CBR1000RR"), (5, "Honda", "CBR1000RR"),  # unknown, 2 rows
            (6, "Ducati", "Panigale V4"),                          # unknown, 1 row
        ])
        assert census(db) == {"Honda": [{"model": "CBR1000RR", "rows": 2}],
                              "Ducati": [{"model": "Panigale V4", "rows": 1}]}

    def test_the_make_filter(self, tmp_path):
        db = _db(tmp_path, [(1, "Honda", "CBR1000RR"), (2, "Ducati", "Panigale V4")])
        assert list(census(db, "Ducati")) == ["Ducati"]

    def test_nothing_unknown_is_an_empty_census_not_an_error(self, tmp_path):
        assert census(_db(tmp_path, [(1, "Honda", "PCX 150")])) == {}
