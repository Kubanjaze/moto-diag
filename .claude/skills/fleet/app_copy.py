"""The phone app's copy of the API's description, refreshed with no model.

Phase 403 (F276; the operator's K84: the fleet may write one file of
moto-diag-mobile, `api-schema/openapi.json`, on a phase branch only and
never `main`). Gate 11 (`tests/test_phase205_gate11.py`) compares
`create_app().openapi()` with that file; the fence mounts the app's
repository read-only, so a phase that changes the description used to stop
until the operator refreshed the file by hand (372, twice).

- `GENERATOR`: the method the operator's blocks used on 372, run by the
  dispatcher in the fence with no network and no model:
  `json.dumps(create_app().openapi(), indent=2, ensure_ascii=False) + "\\n"`.
  It reproduces moto-diag-mobile `993fadc` from backend `cbfa766`, `d292eef`
  from `76bdea5` and `13b6e68` from `a2d72c6`, byte for byte
  (`403_step0.md`, S0-3; held by `tests/test_phase403_app_copy.py`).
- `commit_copy`: the one file committed on the app's branch named as the
  phase branch, in the fleet's own copy of the app; refused on any other
  branch, when anything else would change, or when nothing does.
"""
from __future__ import annotations

import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from rank_call import Stop  # noqa: E402

#: The one file of the app's repository the fleet may write.
SCHEMA = "api-schema/openapi.json"
#: Where the generator writes, in its run folder (`/fleet/run` in the fence).
OUT_NAME = "openapi.json"
GATE11 = "tests/test_phase205_gate11.py"
GATE11_CMD = [".venv/bin/python", "-m", "pytest", "-q", "-p", "no:cacheprovider", GATE11]
#: argv[1]: the file to write; argv[2], when given: a `src` folder to import
#: the app from first (the test's exported old commits).
GENERATOR = """\
import json, sys
if len(sys.argv) > 2:
    sys.path.insert(0, sys.argv[2])
from motodiag.api.app import create_app
text = json.dumps(create_app().openapi(), indent=2, ensure_ascii=False) + "\\n"
with open(sys.argv[1], "w", encoding="utf-8", newline="\\n") as f:
    f.write(text)
"""


def generate_cmd() -> list[str]:
    """The generator as the dispatcher runs it in the fence, on the clone's
    own code (the fleet's virtualenv installs it, editable)."""
    return [".venv/bin/python", "-I", "-c", GENERATOR, f"/fleet/run/{OUT_NAME}"]


def branch_problem(branch: str, phase: str) -> str | None:
    """Why the app's copy may not go on `branch`, or None (K84: a phase
    branch only, never `main`)."""
    if branch in ("main", "master") or not re.fullmatch(
            rf"phase-{re.escape(phase)}-[A-Za-z0-9._-]+", branch) or "-stopped-" in branch:
        return (f"the app's copy goes only on the app's branch named as phase {phase}'s branch, "
                f"never on {branch!r}")
    return None


def _git(repo: pathlib.Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)


def commit_copy(mobile: pathlib.Path, branch: str, phase: str, data: bytes, backend: str,
                author: tuple[str, str]) -> str:
    """`data` as `SCHEMA` on the app's `branch` in the fleet's own copy,
    committed; returns the commit. The branch starts from the app's
    `origin/<branch>` when GitHub has it, else from `origin/main`."""
    problem = branch_problem(branch, phase)
    if problem:
        raise Stop(problem)
    if not (mobile / ".git").exists():
        raise Stop(f"the fleet has no copy of the app at {mobile}")
    if _git(mobile, "fetch", "-q", "--prune", "origin").returncode != 0:
        raise Stop("the fleet's copy of the app could not be fetched")
    has = _git(mobile, "rev-parse", "--verify", "-q", f"refs/remotes/origin/{branch}")
    base = f"origin/{branch}" if has.returncode == 0 else "origin/main"
    r = _git(mobile, "checkout", "-q", "-f", "-B", branch, base)
    if r.returncode != 0:
        raise Stop(f"the app's branch {branch} could not be made: {r.stderr.strip()[:200]}")
    _git(mobile, "clean", "-qfd")
    (mobile / SCHEMA).parent.mkdir(parents=True, exist_ok=True)
    (mobile / SCHEMA).write_bytes(data)
    changed = sorted(ln[3:] for ln in _git(mobile, "status", "--porcelain",
                                           "--untracked-files=all").stdout.splitlines())
    if not changed:
        raise Stop(f"the regenerated description is the same as the app's copy on {base}: "
                   "nothing to commit")
    if changed != [SCHEMA]:
        raise Stop(f"refused: more than the one file would change in the app: {changed[:5]}")
    _git(mobile, "add", "--", SCHEMA)
    msg = (f"Phase {phase}: the API's description from backend {backend[:12]}\n\n"
           "Regenerated by the fleet's dispatcher with no model (Phase 403):\n"
           "json.dumps(create_app().openapi(), indent=2, ensure_ascii=False) + newline.\n")
    r = _git(mobile, "-c", f"user.name={author[0]}", "-c", f"user.email={author[1]}",
             "commit", "-q", "-m", msg)
    if r.returncode != 0:
        raise Stop(f"the app's copy could not be committed: {(r.stderr or r.stdout).strip()[:200]}")
    names = _git(mobile, "diff", "--name-only", f"{base}..HEAD").stdout.split()
    if names != [SCHEMA]:
        raise Stop(f"refused: the app's branch would change {names[:5]}, not only {SCHEMA}")
    return _git(mobile, "rev-parse", "HEAD").stdout.strip()
